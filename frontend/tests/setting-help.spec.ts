import { test, expect } from './fixtures'
import { showEditorSettings } from './editor-settings'

test('editor help distinguishes sizing and supports hover, keyboard and dismissal', async ({
  page,
}) => {
  await page.goto('/#/templates/new')
  const automatic = page.getByRole('checkbox', { name: 'Automatic label length', exact: true })
  const original = await automatic.isChecked()
  const info = page.getByRole('button', { name: 'About Automatic label length', exact: true })
  await info.hover()
  const tooltip = page.getByRole('tooltip')
  await expect(tooltip).toContainText('It does not resize text boxes')
  await expect(tooltip).toContainText('Layout → Fit text box width to content')
  await tooltip.hover()
  await expect(tooltip).toBeVisible()
  await page.mouse.move(0, 0)
  await expect(tooltip).toBeHidden()
  await info.focus()
  await expect(tooltip).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(tooltip).toBeHidden()
  await expect(info).toBeFocused()
  await info.click()
  await expect(tooltip).toBeVisible()
  await info.click()
  await expect(tooltip).toBeHidden()
  expect(await automatic.isChecked()).toBe(original)
  await page.getByRole('button', { name: 'Add text', exact: true }).click()
  await showEditorSettings(page, 'Position & size')
  const fitInfo = page.getByRole('button', { name: 'About Fit text box to content', exact: true })
  await fitInfo.focus()
  await expect(tooltip).toContainText('including variable values and logic')
  await page.keyboard.press('Tab')
  await expect(tooltip).toBeHidden()
  await showEditorSettings(page, 'Typography')
  await page.getByRole('button', { name: 'About Font size (mm)', exact: true }).click()
  await expect(tooltip).toContainText('The maximum size of the text')
  // The fixed tooltip escapes the inspector's clipping and remains within the viewport.
  const box = await tooltip.boundingBox()
  expect(box).not.toBeNull()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.y).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: 'test-results/setting-help-desktop.png', animations: 'disabled' })
  await page.getByRole('textbox', { name: 'Template name', exact: true }).click()
  await expect(tooltip).toBeHidden()
})

test.describe('touch help', () => {
  test.use({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
  test('opens by tapping without changing a setting and fits a narrow screen', async ({ page }) => {
    await page.goto('/#/templates/new')
    const automatic = page.getByRole('checkbox', { name: 'Automatic label length', exact: true })
    const original = await automatic.isChecked()
    const info = page.getByRole('button', { name: 'About Automatic label length', exact: true })
    await info.tap()
    const tooltip = page.getByRole('tooltip')
    await expect(tooltip).toContainText('It does not resize text boxes')
    const box = await tooltip.boundingBox()
    const target = await info.boundingBox()
    expect(target!.height).toBeGreaterThanOrEqual(44)
    expect(target!.width).toBeGreaterThanOrEqual(44)
    expect(box!.x).toBeGreaterThanOrEqual(12)
    expect(box!.x + box!.width).toBeLessThanOrEqual(378)
    expect(box!.y + box!.height).toBeLessThanOrEqual(844)
    expect(await automatic.isChecked()).toBe(original)
    await page.screenshot({ path: 'test-results/setting-help-mobile.png', animations: 'disabled' })
    await info.tap()
    await expect(tooltip).toBeHidden()
    await info.tap()
    await page.getByText('Ignore out-of-bounds objects', { exact: true }).tap()
    await expect(tooltip).toBeHidden()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  })
})
